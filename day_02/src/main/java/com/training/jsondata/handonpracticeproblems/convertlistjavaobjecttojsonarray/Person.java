package com.training.jsondata.handonpracticeproblems.convertlistjavaobjecttojsonarray;

class Person {
    private String name;
    private int age;

    // Constructor
    public Person(String name, int age) {
        this.name = name;
        this.age = age;
    }

    // Getters and setters
    public String getName() { return name; }
    public int getAge() { return age; }
}